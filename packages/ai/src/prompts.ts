export function userPromptForProAction(
  action: ProAction,
  text: string,
  question?: string,
  pageTitle?: string,
  pageUrl?: string,
): string {
  const parts: string[] = [];
  if (pageTitle) parts.push(`Заголовок страницы: ${pageTitle}`);
  if (pageUrl) parts.push(`Адрес страницы: ${pageUrl}`);
  parts.push("Фрагмент:");
  parts.push("«" + text + "»");
  if (action === "ask" && question) {
    parts.push("Вопрос пользователя: " + question);
  }
  return parts.join("\n");
}
