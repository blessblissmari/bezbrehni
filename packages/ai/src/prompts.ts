export function userPromptForCheck(text: string, pageTitle?: string, pageUrl?: string) {
  const ctx: string[] = [];
  if (pageTitle) ctx.push(`Заголовок страницы: ${pageTitle}`);
  if (pageUrl) ctx.push(`Адрес страницы: ${pageUrl}`);
  ctx.push("Фрагмент для оценки:");
  ctx.push("«" + text + "»");
  return ctx.join("\n");
}

